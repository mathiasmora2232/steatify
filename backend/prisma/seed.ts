/**
 * Achievement catalog. Rules are DATA, not code: the achievements engine (Phase 3)
 * reads `rule` and evaluates it against a user's metrics, so adding a new badge
 * is a row insert — no deploy. `metric` keys map to computed user stats.
 */
interface AchievementSeed {
  code: string;
  name: string;
  description: string;
  emoji: string;
  category: AchievementCategory;
  tier: number;
  rule: { metric: string; op: string; threshold: number };
  points: number;
  secret?: boolean;
}

